#!/bin/bash
# 容器入口：首次运行生成服务器配置、解包内置地图、安装插件，然后启动 Paper。
set -euo pipefail

DATA_DIR="${DATA_DIR:-/data}"
SERVER_JAR="/opt/server/paper.jar"
PLUGIN_SRC="/opt/server/plugins-src"
mkdir -p "$DATA_DIR"

# ---------------------------------------------------------------------------
# EULA
# ---------------------------------------------------------------------------
if [ ! -f "$DATA_DIR/eula.txt" ]; then
    echo "eula=true" > "$DATA_DIR/eula.txt"
    echo "[init] 已写入 eula.txt（eula=true），表示你同意 Minecraft EULA"
fi

# ---------------------------------------------------------------------------
# server.properties：默认关闭白名单与正版验证、关闭下界
# ---------------------------------------------------------------------------
if [ ! -f "$DATA_DIR/server.properties" ]; then
    cat > "$DATA_DIR/server.properties" <<'EOF'
# Generated by ThePitGay-NextGen docker image
server-port=25565
motd=ThePitGay-NextGen (Paper 1.21.8)
level-name=pit_arena
level-type=minecraft\:normal
online-mode=false
white-list=false
enforce-whitelist=false
allow-nether=false
allow-flight=true
spawn-protection=0
max-players=100
view-distance=8
simulation-distance=6
enable-command-block=false
generate-structures=false
difficulty=normal
gamemode=adventure
force-gamemode=true
pvp=true
enable-status=true
sync-chunk-writes=false
EOF
    echo "[init] 已生成 server.properties（offline 模式、白名单关闭、下界关闭）"
fi

# 允许用环境变量强制覆盖关键项（每次启动都会生效）
set_prop() {
    local key="$1" value="$2"
    if grep -q "^${key}=" "$DATA_DIR/server.properties" 2>/dev/null; then
        sed -i "s|^${key}=.*|${key}=${value}|" "$DATA_DIR/server.properties"
    else
        echo "${key}=${value}" >> "$DATA_DIR/server.properties"
    fi
}

set_prop "server-port" "${SERVER_PORT:-25565}"
set_prop "online-mode" "${ONLINE_MODE:-false}"
set_prop "white-list" "${WHITE_LIST:-false}"
set_prop "allow-nether" "${ALLOW_NETHER:-false}"
set_prop "level-name" "${LEVEL_NAME:-pit_arena}"
set_prop "max-players" "${MAX_PLAYERS:-100}"
set_prop "motd" "${MOTD:-ThePitGay-NextGen (Paper 1.21.8)}"

# ---------------------------------------------------------------------------
# bukkit.yml：关闭末地
# ---------------------------------------------------------------------------
if [ ! -f "$DATA_DIR/bukkit.yml" ]; then
    cat > "$DATA_DIR/bukkit.yml" <<'EOF'
# Generated by ThePitGay-NextGen docker image
settings:
  allow-end: false
  warn-on-overload: true
  permissions-file: permissions.yml
  update-folder: update
  plugin-profiling: false
  connection-throttle: 4000
  query-plugins: true
  deprecated-verbose: default
  shutdown-message: 服务器正在关闭
  minimum-api: none
EOF
    echo "[init] 已生成 bukkit.yml（末地关闭）"
fi

# ---------------------------------------------------------------------------
# 插件
# ---------------------------------------------------------------------------
mkdir -p "$DATA_DIR/plugins"
install_plugin() {
    local src="$1" dst="$2"
    if [ ! -f "$DATA_DIR/plugins/$dst" ] || [ "${FORCE_PLUGIN_UPDATE:-false}" = "true" ]; then
        cp -f "$src" "$DATA_DIR/plugins/$dst"
        echo "[init] 已安装插件 $dst"
    fi
}
install_plugin "$PLUGIN_SRC/ThePitGay-V.jar" "ThePitGay-V.jar"
install_plugin "$PLUGIN_SRC/LuckPerms-Bukkit.jar" "LuckPerms-Bukkit.jar"

# ---------------------------------------------------------------------------
# 内置地图：首次运行从插件 jar 解出 pit_arena，避免 Paper 生成空地图
# ---------------------------------------------------------------------------
LEVEL_NAME="${LEVEL_NAME:-pit_arena}"
if [ ! -d "$DATA_DIR/$LEVEL_NAME/region" ] && [ "$LEVEL_NAME" = "pit_arena" ]; then
    TMP_MAP="$(mktemp -d)"
    if unzip -o -q "$PLUGIN_SRC/ThePitGay-V.jar" "maps/pit_arena.zip" -d "$TMP_MAP" 2>/dev/null; then
        unzip -o -q "$TMP_MAP/maps/pit_arena.zip" -d "$TMP_MAP/map"
        rm -rf "$DATA_DIR/pit_arena"
        mkdir -p "$DATA_DIR/pit_arena"
        # 压缩包内顶层目录为 world/，去掉后作为地图根目录
        cp -a "$TMP_MAP/map/world/." "$DATA_DIR/pit_arena/"
        rm -f "$DATA_DIR/pit_arena/uid.dat" "$DATA_DIR/pit_arena/session.lock"
        echo "[init] 已解包内置地图 pit_arena"
    else
        echo "[init] 警告：未能从插件 jar 解出内置地图，将由服务器自行生成"
    fi
    rm -rf "$TMP_MAP"
fi

# ---------------------------------------------------------------------------
# 启动
# ---------------------------------------------------------------------------
cd "$DATA_DIR"
MEMORY="${MEMORY:-4G}"
JAVA_FLAGS="${JAVA_FLAGS:--XX:+UseG1GC -XX:+ParallelRefProcEnabled -XX:MaxGCPauseMillis=200 -XX:+UnlockExperimentalVMOptions -XX:+DisableExplicitGC -XX:G1NewSizePercent=30 -XX:G1MaxNewSizePercent=40 -XX:G1HeapRegionSize=8M -XX:G1ReservePercent=20 -XX:G1HeapWastePercent=5 -XX:G1MixedGCCountTarget=4 -XX:InitiatingHeapOccupancyPercent=15 -XX:G1MixedGCLiveThresholdPercent=90 -XX:G1RSetUpdatingPauseTimePercent=5 -XX:SurvivorRatio=32 -XX:MaxTenuringThreshold=1 -XX:+PerfDisableSharedMem}"

echo "[start] 启动 Paper 1.21.8（内存 $MEMORY，offline=$ONLINE_MODE，whitelist=$WHITE_LIST，nether=$ALLOW_NETHER，end=false）"
exec java -Xms"$MEMORY" -Xmx"$MEMORY" $JAVA_FLAGS \
    -Dfile.encoding=UTF-8 -Dsun.stdout.encoding=UTF-8 -Dsun.stderr.encoding=UTF-8 \
    -Dio.netty.native.workdir=/tmp \
    -jar "$SERVER_JAR" --nogui
